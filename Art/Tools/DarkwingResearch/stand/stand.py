"""Human playthrough stand for the original Darkwing Duck ROM, with port comparison.

  record   start a session: Mesen's own window, keys, picture and sound, with Mesen's own
           movie recorder capturing the pad (--recordMovie, no clicks needed);
           --headless runs mesen-agent with a synthesized track instead, for tooling tests
  movie    convert an existing Mesen .mmo into a session (e.g. one recorded from the menu)
  replay   replay the recorded pad track in the original N times, prove the traces identical
  unity    translate the same track into the existing Unity ReplaySpec and run it in the port
  diff     first divergence frame original vs port, plus a PNG neighbourhood on both sides

A session lives in Art/Playthroughs/<utc-stamp>/ (git-ignored, never auto-deleted):
  meta.json        ROM hashes, emulator build, settings, frame convention, key map
  movie.mmo        Mesen's own recording: a zip with Input.txt (one line per emulated frame)
  movie.json       what the converter read out of it (frames, device fields, game settings)
  input.bin        one NES pad byte per emulated frame (bit order = NesButtons.ToByte)
  trace.csv        per-frame fingerprints of the original, regenerated by the deterministic replay
  replay1/2/...    deterministic replay runs, optional frame_*.png shots
  unity/           port spec + port trace.csv + port frame_*.png
  diff/            first divergence report + original/port/diff PNGs

Recording ends when the user closes the Mesen window; Mesen writes the movie on stop.
The pad track is a re-simulation from power-on, so loading a state or rewinding *during* a
recording is not supported: the movie keeps its frame grid, the console underneath it jumps, and
nothing in the .mmo can reveal that afterwards. The headless replay detects such a jump itself
(stand.lua logs INVALID on stateLoaded/stateSaved) and refuses the session.
"""
from __future__ import annotations
import argparse, base64, hashlib, json, math, shutil, subprocess, sys, zipfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents if (p / 'ProjectSettings').is_dir())
ROM = ROOT / "Art/Darkwing Duck (USA).nes"
ROM_SHA256 = "1271dce8678ffc261e2c05cc785ae53e29ac1f9ecf6265a4265bed825abb0a00"
MESEN = ROOT / "Art/Tools/DarkwingResearch/vendor/Mesen2/Mesen.exe"
AGENT = ROOT / "Art/Tools/DarkwingResearch/vendor/mesen-agent/mesen-agent.exe"
TEMPLATE = Path(__file__).with_name("stand.lua.in")
PLAY = ROOT / "Art/Playthroughs"
KEYMAP = ("arrows=D-pad, Z=A, X=B, Enter=Start, LeftShift=Select "
          "(Mesen default player-1 keys, identical to the Unity stand keys)")
CONVENTION = ("input.bin byte i (0-based) is the pad state Mesen sampled at the i-th InputPolled "
              "event of the run; poll/frame numbering starts at 1 and one poll = one NES frame. "
              "The port replay feeds the same byte to port frame i+1 (its own 1-based counter). "
              "Comparison therefore starts at the first emulated frame after power-on reset.")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def render(out: Path, input_path: Path, shots, full_every: int) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    text = TEMPLATE.read_text(encoding="utf-8")
    for token, value in (("__DIR__", json.dumps(out.as_posix())),
                         ("__INPUT__", json.dumps(input_path.as_posix())),
                         ("__SHOT_LIST__", ",".join(str(int(s)) for s in shots)),
                         ("__FULL_EVERY__", str(full_every))):
        text = text.replace(token, value)
    lua = out / "stand.lua"
    lua.write_text(text, encoding="utf-8")
    return lua


def run_agent(lua: Path, frames: int, out: Path, timeout: int = 600, state=None, tolerate=()):
    argv = [str(AGENT), str(ROM), "--home", str(out / "home"), "--frames", str(frames),
            "--timeout", str(timeout), "--lua", str(lua), "--lua-allow-io"]
    if state:
        argv += ["--load-state", str(Path(state).resolve())]
    run = subprocess.run(argv, cwd=ROOT, capture_output=True, text=True,
                         encoding="utf-8", errors="replace", timeout=timeout + 60)
    (out / "agent_stderr.txt").write_text(run.stderr, encoding="utf-8")
    events = [json.loads(line) for line in run.stdout.splitlines() if line.strip().startswith("{")]
    summaries = [e for e in events if e.get("event") == "summary"]
    summary = summaries[-1] if summaries else None
    # A tolerated stop reason also carries mesen-agent's own non-zero exit code (rc=4 for timeout),
    # so the return code cannot be the failure test on its own.
    tolerated = summary is not None and summary.get("reason") in tolerate
    if summary is None or (run.returncode and not tolerated):
        raise RuntimeError(f"mesen-agent failed (rc={run.returncode}): "
                           f"{(summary if summary else run.stderr[-400:])}")
    if not summary.get("ok") and not tolerated:
        raise RuntimeError(f"mesen-agent failed (rc={run.returncode}): {summary}")
    return summary


def track_bytes(session: Path) -> bytes:
    return (session / "input.bin").read_bytes()


def invalid_lines(session: Path):
    bad = []
    for log in [session / "stand_log.txt", *session.glob("replay*/stand_log.txt")]:
        if log.is_file():
            bad += [f"{log.parent.name}/{log.name}: {line}"
                    for line in log.read_text(encoding="utf-8").splitlines()
                    if "INVALID" in line or "WARN" in line]
    return bad


def write_meta(session: Path):
    meta = {"rom": {"path": str(ROM), "sha256": sha256(ROM),
                    "sha1": hashlib.sha1(ROM.read_bytes()).hexdigest().upper()},
            "emulator": {"gui": str(MESEN), "gui_sha256": sha256(MESEN) if MESEN.is_file() else None,
                         "headless_agent": AGENT.name, "headless_agent_sha256": sha256(AGENT),
                         "core": "Mesen 2.1.1", "region": "Ntsc"},
            "settings": "Mesen GUI keeps its configuration next to the executable "
                        f"({MESEN.parent / 'settings.json'}); the stand reads it and reports it, it "
                        "does not rewrite it (Mesen discards an externally written settings.json). "
                        "Headless runs use mesen-agent 2.1.1 defaults.",
            "capture": "Mesen's own movie recorder (--recordMovie), one input line per emulated "
                       "frame; input.bin is the port-1 pad column of that log, converted with "
                       "Mesen's own button order UDLRSsBA.",
            "keymap": KEYMAP, "frame_convention": CONVENTION,
            "start_point": "power-on reset (frame 1); the port is not given any offset or skip",
            "createdUtc": datetime.now(timezone.utc).isoformat(timespec="seconds")}
    (session / "meta.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")


def read_trace(path: Path):
    """trace.csv rows -> (dict of shared fields per poll, {poll: (nt_sum, oam_sum)})."""
    rows, fulls = {}, {}
    if not path.is_file():
        return rows, fulls
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# full"):
            parts = dict(p.split("=") for p in line.split()[3:])
            fulls[int(line.split()[2])] = (int(parts["nt"]), int(parts["oam"]))
        elif line and not line.startswith("poll,"):
            f = line.split(",")
            rows[int(f[0])] = {"abs_frame": int(f[1]), "pollCnt": int(f[2]), "pc": f[3],
                               "x": int(f[4]), "y": int(f[5]), "state": int(f[6]),
                               "ctrl": int(f[7]), "mask": int(f[8]), "ram_sum": int(f[9]),
                               "pal_sum": int(f[10])}
    return rows, fulls


def read_port_trace(path: Path):
    """Read named columns: current exports include gameFrame; older ones do not."""
    import csv
    rows, fulls = {}, {}
    if not path.is_file():
        return rows, fulls
    header = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# full"):
            parts = dict(p.split("=") for p in line.split()[3:])
            fulls[int(line.split()[2])] = (int(parts["nt"]), int(parts["oam"]))
        elif not line or line.startswith("#"):
            continue
        else:
            values = next(csv.reader([line]))
            if header is None:
                header = values
                required = {"frame", "x", "y", "state", "ctrl", "mask", "pal_sum"}
                if not required.issubset(header) or len(set(header)) != len(header):
                    raise ValueError("Missing/duplicate port trace columns")
                continue
            if len(values) != len(header):
                raise ValueError("Truncated/extra port trace columns")
            row = dict(zip(header, values))
            frame = int(row["frame"])
            if frame != len(rows) + 1:
                raise ValueError("Missing/duplicate/out-of-order port trace frame")
            rows[frame] = {key: int(row[key]) for key in ("x", "y", "state", "ctrl", "mask", "pal_sum")}
    return rows, fulls


def ranges(track: bytes):
    """Run-length encode the pad track into the existing ReplaySpec {first,last,buttons} form."""
    out = []
    for i, value in enumerate(track):
        if out and value == out[-1]["buttons"]:
            out[-1]["last"] = i + 1
        else:
            out.append({"first": i + 1, "last": i + 1, "buttons": value})
    return out


PAD_BITS = {"right": 1, "left": 2, "down": 4, "up": 8, "start": 16, "select": 32, "b": 64, "a": 128}


def parse_schedule(entries, frames: int) -> bytes:
    """`0:right@100-120` (Mesen's own syntax, 1-based inclusive) -> one pad byte per frame."""
    track = bytearray(frames)
    for entry in entries:
        name, rng = entry.split(":", 1)[1].split("@", 1)
        lo, _, hi = rng.partition("-")
        for f in range(int(lo), min(int(hi or lo), frames) + 1):
            track[f - 1] |= PAD_BITS[name]
    return bytes(track)


# Mesen's movie input log stores a pad as 8 characters, one per button, in the order of its own
# button enum: Core/NES/Input/NesController.h has `Up = 0, Down, Left, Right, Start, Select, B, A`
# and the character string "UDLRSsBA" (lowercase s because S is taken by Start). '.' = released.
# MovieRecorder::RecordInput then writes "|" + device->GetTextState() for every control device, so
# a plain two-pad NES session logs |<2-char device>|<port 1>|<port 2>.
MOVIE_PAD_CHARS = dict(zip("UDLRSsBA", ("up", "down", "left", "right", "start", "select", "b", "a")))
KEY_NAMES = {23: "Left", 24: "Up", 25: "Right", 26: "Down", 44: "X", 60: "LeftShift",
             62: "Z", 66: "Enter", 4: "A", 5: "B", 6: "C"}


def gui_config() -> dict:
    """Read what the vendored Mesen GUI is actually set to. The stand never rewrites it: a
    settings.json produced outside Mesen is discarded on exit (measured 2026-10-19), so the only
    honest check is to report the live values and let a mismatch be visible."""
    f = MESEN.parent / "settings.json"
    if not f.is_file():
        return {"file": str(f), "error": "missing - Mesen has not finished its first run yet"}
    s = json.loads(f.read_bytes().decode("utf-8-sig"))
    p1 = s["Nes"]["Port1"]["Mapping1"]
    keys = {b: KEY_NAMES.get(c, f"code{c}") for b, c in p1.items()
            if b in ("Up", "Down", "Left", "Right", "A", "B", "Start", "Select") and c}
    pref = s["Preferences"]
    return {"file": str(f), "player1Keys": keys,
            "pauseWhenInBackground": pref.get("PauseWhenInBackground"),
            "allowBackgroundInput": pref.get("AllowBackgroundInput"),
            "rewindEnabled": pref.get("EnableRewind"),
            "movieRecordFrom": s.get("MovieRecord", {}).get("RecordFrom")}


def ingest_movie(mmo: Path) -> tuple[bytes, dict]:
    """Mesen's own .mmo -> the one-pad-byte-per-frame track the rest of the stand consumes."""
    with zipfile.ZipFile(mmo) as z:
        names = z.namelist()
        if "Input.txt" not in names:
            raise SystemExit(f"{mmo}: no Input.txt in this movie (found {names})")
        lines = z.read("Input.txt").decode("utf-8").splitlines()
        settings = dict(line.split(" ", 1) for line in
                        z.read("GameSettings.txt").decode("utf-8").splitlines() if " " in line) \
            if "GameSettings.txt" in names else {}
    track = bytearray()
    fields, presses = None, {}
    for i, line in enumerate(lines):
        if not line.startswith("|"):
            raise SystemExit(f"{mmo}: line {i + 1} is not a Mesen input line: {line!r}")
        cols = line[1:].split("|")
        if fields is None:
            fields = [len(c) for c in cols]
            if 8 not in fields:
                raise SystemExit(f"{mmo}: no 8-character pad field in {cols}, the format changed")
            pad_at = fields.index(8)
        elif [len(c) for c in cols] != fields:
            raise SystemExit(f"{mmo}: line {i + 1} has {len(cols)} fields, the first line had {len(fields)}")
        byte = 0
        for pos, ch in enumerate(cols[pad_at]):
            if ch != ".":
                name = MOVIE_PAD_CHARS.get(ch)
                if name is None:
                    raise SystemExit(f"{mmo}: frame {i + 1} position {pos} has unknown char {ch!r}")
                byte |= PAD_BITS[name]
        for j, col in enumerate(cols):
            if j != pad_at:
                for ch in set(col) - {"."}:
                    presses[f"field{j}:{ch}"] = presses.get(f"field{j}:{ch}", 0) + 1
        track.append(byte)
    info = {"movie": str(mmo), "frames": len(track), "fields": fields, "padField": pad_at,
            "nonPadPresses": presses, "gameSettings": {k: v for k, v in settings.items()
                                                       if k.startswith("nes.") or k.startswith("Movie")}}
    return bytes(track), info


def cmd_record(args):
    assert sha256(ROM) == ROM_SHA256, "source ROM changed"
    session = PLAY / (args.session or datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ"))
    if session.exists():
        raise SystemExit(f"session exists, refusing to overwrite: {session}")
    session.mkdir(parents=True)
    write_meta(session)
    if args.headless:
        # mesen-agent applies its own --input schedule to the console but Lua's emu.getInput does
        # not see it (measured: a 250-frame run with right@100-120 recorded all zeros), so the
        # headless self-test synthesizes the track and drives it through the replay path instead.
        (session / "input.bin").write_bytes(parse_schedule(args.input, args.headless))
        lua = render(session, session / "input.bin", [], args.full_every)
        summary = run_agent(lua, args.headless, session)
        print(json.dumps({"session": str(session), "syntheticTrack": True,
                          "summary": summary}, indent=2))
    else:
        assert MESEN.is_file(), f"Mesen GUI missing: {MESEN}"
        movie = session / "movie.mmo"
        cfg = gui_config()
        # Mesen's own window, keys, picture, sound AND recorder: --recordMovie starts capturing
        # as soon as the ROM is loaded, so the human path needs no menu clicks at all.
        proc = subprocess.Popen([str(MESEN), str(ROM), f"--recordMovie={movie}"], cwd=ROOT)
        print(f"session:  {session}\nkeys:     {KEYMAP}\n"
              f"config:   {json.dumps(cfg, ensure_ascii=False)}\n"
              "click the Mesen window once - with allowBackgroundInput off its keys only reach\n"
              "the game while that window has focus. Then play, and close the window to stop.\n"
              "no save states and no rewind while recording (see the module docstring).",
              flush=True)
        proc.wait()
        if not movie.is_file():
            raise SystemExit(f"Mesen produced no movie at {movie}: the recorder did not run. "
                             "Mesen only honours --recordMovie when the ROM loads in that same "
                             "instance, so a leftover Mesen window (SingleInstance is on) or a "
                             "cancelled first-run dialog is the first thing to check.")
        track, info = ingest_movie(movie)
        (session / "input.bin").write_bytes(track)
        (session / "movie.json").write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")
        print(json.dumps({"movie": info["frames"], "fields": info["fields"],
                          "padField": info["padField"], "nonPadPresses": info["nonPadPresses"]},
                         indent=2))
        if not any(track):
            print("WARNING: every frame of this session is an idle pad. Either nothing was "
                  "pressed or the pad is not the field this converter reads "
                  f"(fields={info['fields']}, padField={info['padField']}).")
        print("next:\n"
              f"  python {Path(__file__).name} replay {session}\n"
              f"  python {Path(__file__).name} unity  {session}\n"
              f"  python {Path(__file__).name} diff   {session} --png")
    bad = invalid_lines(session)
    track = track_bytes(session) if (session / "input.bin").is_file() else b""
    print(json.dumps({"bytes": len(track), "invalid_state_events": bad}, indent=2))
    if bad:
        print("Session is NOT replayable (state load / rewind during recording).")


def cmd_movie(args):
    """Turn a Mesen movie recorded any other way (menu > Movies > Record) into a session."""
    mmo = Path(args.movie).resolve()
    session = PLAY / (args.session or mmo.stem)
    if session.exists() and (session / "input.bin").is_file():
        raise SystemExit(f"session already has a track, refusing to overwrite: {session}")
    session.mkdir(parents=True, exist_ok=True)
    write_meta(session)
    track, info = ingest_movie(mmo)
    (session / "input.bin").write_bytes(track)
    (session / "movie.json").write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"session": str(session), "frames": len(track), "fields": info["fields"],
                      "padField": info["padField"], "nonPadPresses": info["nonPadPresses"],
                      "pressedFrames": sum(1 for b in track if b)}, indent=2))


def compare_traces(paths):
    """Line-by-line compare of two or more traces.

    Mesen randomizes work RAM and palette RAM at power-on and neither the agent CLI nor a
    settings file can pin it, so a run that starts at reset can only converge once the ROM's
    own RAM-clear loop has run. That leading window is reported as a count, never hidden; any
    divergence after it is a real failure of reproducibility. A --state start removes the window
    entirely, because the save state fixes the whole console.
    """
    texts = [p.read_text(encoding="utf-8").splitlines() for p in paths]
    if len({len(t) for t in texts}) != 1:
        return {"identical": False, "reason": f"different lengths {[len(t) for t in texts]}"}
    diff = {i for i, cols in enumerate(zip(*texts)) if len(set(cols)) > 1}
    first = min(diff, default=0)
    end = first
    while end in diff:
        end += 1
    outside = sorted(diff - set(range(first, end)))
    return {"identical": not outside, "differingLines": len(diff),
            "powerOnWindowLines": end - first, "powerOnWindowStart": first,
            "linesCompared": len(texts[0]),
            "outsideWindow": [{"line": i, "values": [t[i] for t in texts]} for i in outside[:5]]}


def cmd_replay(args):
    session = Path(args.session).resolve()
    track = track_bytes(session)
    if invalid_lines(session):
        raise SystemExit(f"{session}: session invalidated by a state load/rewind, refusing")
    if not track:
        raise SystemExit(f"{session}: no input.bin recorded")
    # mesen-agent executes at real time (1 s per 60 recorded frames). It also overshoots --frames on
    # long tracks: a 24261-frame track asked for with --frames 24261 ran to 36046 and then to 38885
    # frames with reason "timeout" instead of "frame_limit", while --frames 600/120/6000 all stopped
    # exactly on the limit. The margin below bounds that overshoot instead of paying for a 60 %
    # empty run; what proves the track was replayed is the traced-frame check, not the stop reason.
    budget = args.timeout or max(120, math.ceil(len(track) / 60 * 1.15) + 30)
    print(f"replay: {len(track)} frames, ~{len(track) / 60:.0f} s of emulation per run, "
          f"agent timeout {budget} s", flush=True)
    shots = [int(s) for s in (args.png.split(",") if args.png else [])]
    traces, runs = [], []
    for run in range(1, args.runs + 1):
        out = (Path(args.output).resolve() if args.output else session) / f"replay{run}"
        lua = render(out, session / "input.bin", shots, args.full_every)
        summary = run_agent(lua, len(track), out, timeout=budget, state=args.state,
                            tolerate=("timeout",))
        traced = len(read_trace(out / "trace.csv")[0])
        if traced != len(track):
            raise SystemExit(f"replay{run}: only {traced} of {len(track)} frames were fingerprinted "
                             f"(agent {summary}) - raise --timeout, this run was cut short")
        traces.append(out / "trace.csv")
        runs.append({k: summary.get(k) for k in ("reason", "frames_executed", "final_frame")})
        print(f"replay{run}: {traced} frames, {len(list(out.glob('frame_*.png')))} PNGs, "
              f"agent {runs[-1]}", flush=True)
    report = {"trackBytes": len(track), "runs": args.runs, "agentRuns": runs,
              "startState": str(args.state) if args.state else "power-on reset",
              "traces": [hashlib.sha256(p.read_bytes()).hexdigest() for p in traces],
              "replayVsReplay": compare_traces(traces)}
    rec = session / "trace.csv"
    if rec.is_file() and rec.stat().st_size == traces[0].stat().st_size:
        report["recordVsReplay"] = compare_traces([rec, traces[0]])
    ((Path(args.output).resolve() if args.output else session) / "replay.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))
    if not report["replayVsReplay"]["identical"]:
        raise SystemExit("Replays diverged in the original - the stand is not deterministic")


def run_port(session: Path, shots, full_every: int, output=None, frames=0, audio_state=False, timeout: int = 0) -> dict:
    """Feed the recorded track to the port: same bytes, same frame numbers, cold boot at frame 1."""
    track = track_bytes(session)
    out = Path(output).resolve() if output else session / "unity"
    out.mkdir(parents=True, exist_ok=True)
    spec = {"frames": min(frames,len(track)) if frames else len(track), "inputs": ranges(track), "captures": list(shots),
            "captureAtStart": True,
            "output": out.as_posix(),
            "audioState": audio_state,
            "note": "Pad track from " + str(session) + "; " + CONVENTION}
    (out / "spec.json").write_text(json.dumps(spec), encoding="utf-8")
    (ROOT / "Art/Temp").mkdir(parents=True, exist_ok=True)
    (ROOT / "Art/Temp/stand_spec.json").write_text(json.dumps({
        "spec": str(out / "spec.json"), "session": str(session), "fullEvery": full_every,
        "shots": list(shots), "audioState": audio_state}), encoding="utf-8")
    unity = shutil.which("unity") or str(Path.home() / "AppData/Local/Unity/bin/unity.exe")
    budget = timeout or 270
    timeout_ms = (budget - 30) * 1000 if budget > 30 else budget * 1000
    cmd = [unity, "command", "run_script", "--file", "Art/AgentScripts/StandRoute.cs",
           "--entry", "StandRoute.Run", "--project-path", str(ROOT), "--caller", "plugin",
           "--skill", "unity-cli", "--timeout", str(budget), "--timeout_ms", str(timeout_ms), "--format", "json"]
    run = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=budget + 30)
    (out / "run_script.json").write_text(run.stdout, encoding="utf-8")
    (out / "run_script_err.txt").write_text(run.stderr, encoding="utf-8")
    try:
        response = json.loads(run.stdout)
        inner = (response.get("data") or {}).get("result") or {}
        if run.returncode or response.get("success") is not True or inner.get("success") is not True:
            raise RuntimeError("Port execution failed; see " + str(out / "run_script.json"))
        result = inner.get("result")
    except ValueError:
        result = run.stdout[-400:]
    return {"frames": spec["frames"], "ranges": len(spec["inputs"]), "cliExit": run.returncode,
            "portTrace": str(out / "trace.csv"), "result": result}


def cmd_unity(args):
    shots = [int(s) for s in (args.png.split(",") if args.png else [])]
    print(json.dumps(run_port(Path(args.session).resolve(), shots, args.full_every, args.output, args.frames, args.audio_state, getattr(args, "timeout", 0)), indent=2))


SHARED = ("x", "y", "state", "ctrl", "mask", "pal_sum")


def scan(orig, ofull, port, pfull, start_at):
    """First frame >= start_at where a shared field, then the periodic nt/oam sums, disagree."""
    for poll in sorted(orig):
        if poll < start_at:
            continue
        p = port.get(poll)
        if p is None:
            return poll, ["port trace ended"]
        bad = [f"{k}: original={orig[poll][k]} port={p[k]}" for k in SHARED if orig[poll][k] != p[k]]
        if bad:
            return poll, bad
        if poll in ofull and poll in pfull and ofull[poll] != pfull[poll]:
            return poll, [f"nt/oam sum: original={ofull[poll]} port={pfull[poll]}"]
    extra = sorted(set(port) - set(orig))
    if extra:
        return extra[0], ["extra port trace frame"]
    return None, []


def cmd_diff(args):
    sys.path.insert(0, str(ROOT / "Art/Tools/DarkwingResearch"))
    from compare_frames import read_png_rgb, to_index_map  # existing PNG reader, no new decoder
    from extract_rom import png_gray                       # existing 8-bit PNG writer
    session = Path(args.session).resolve()
    src_dir = session / f"replay{args.run}"
    orig_path = (src_dir / "trace.csv") if (src_dir / "trace.csv").is_file() else (session / "trace.csv")
    orig, ofull = read_trace(orig_path)
    port, pfull = read_port_trace(session / "unity/trace.csv")
    if not port:
        raise SystemExit("no port trace - run: stand.py unity <session> first")
    replay = json.loads((session / "replay.json").read_text(encoding="utf-8")) \
        if (session / "replay.json").is_file() else {}
    if replay.get("startState", "power-on reset") != "power-on reset":
        raise SystemExit(
            f"{session}: the original side starts from {replay['startState']}, but the port cannot "
            "be seeded from a save state (PhysCompare fills its fields one by one for fixed "
            "scenarios). Only a power-on session compares against the port.")
    # Measured irreproducible prefix: the leading lines on which two independent replays of the
    # same track differ because Mesen randomizes work RAM and palette RAM at power-on. It is a
    # property of the emulator, recorded in replay.json, not an offset picked to make a diff pass,
    # and the raw first divergence at frame 1 is still reported.
    rr = replay.get("replayVsReplay") or {}
    window_end = int(rr.get("powerOnWindowStart", 0)) + int(rr.get("powerOnWindowLines", 0)) - 1
    raw, raw_fields = scan(orig, ofull, port, pfull, 1)
    first, why = scan(orig, ofull, port, pfull, max(1, window_end + 1))
    out = session / "diff"
    out.mkdir(exist_ok=True)
    result = {"startPoint": CONVENTION, "irreproduciblePowerOnFrames": max(0, window_end),
              "firstDivergence": raw, "firstDivergenceFields": raw_fields,
              "firstDivergenceAfterPowerOn": first, "fields": why,
              "trace": str(orig_path), "framesOriginal": len(orig), "framesPort": len(port),
              "note": "no divergence in the compared range" if first is None else
                      "later frames are consequences until this one is explained"}
    if first is not None and args.png:
        span = sorted({f for a in range(0, args.neighbourhood + 1)
                       for f in (first - a, first + a) if 1 <= f <= len(track_bytes(session))})
        shots = session / f"replay{args.run}_shots"
        run_agent(render(shots, session / "input.bin", span, args.full_every),
                  max(span), shots,
                  timeout=args.timeout or max(120, math.ceil(max(span) / 60 * 1.6)))
        if not all((session / f"unity/frame_{f}.png").is_file() for f in span):
            run_port(session, span, args.full_every)
            _, pfull = read_port_trace(session / "unity/trace.csv")
        rows = []
        for f in span:
            o, p = shots / f"frame_{f}.png", session / f"unity/frame_{f}.png"
            row = {"frame": f, "original": o.name if o.is_file() else "missing",
                   "port": p.name if p.is_file() else "missing"}
            if o.is_file() and p.is_file():
                ow, oh, orgb = read_png_rgb(o)
                pw, ph, prgb = read_png_rgb(p)
                if (ow, oh) != (pw, ph):
                    row["size"] = f"{ow}x{oh} vs {pw}x{ph}"
                else:
                    oi, ou = to_index_map(ow, oh, orgb)
                    pi, pu = to_index_map(pw, ph, prgb)
                    png_gray(out / f"diff_{f}.png", ow, oh,
                             bytes(255 if a != b else 0 for a, b in zip(oi, pi)))
                    row.update(differentPixels=sum(1 for a, b in zip(oi, pi) if a != b),
                               unmapped=[ou, pu], diff=f"diff_{f}.png")
            rows.append(row)
        result["neighbourhood"] = rows
    (out / "report.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, indent=2))
    if first is not None:
        raise SystemExit(1)


def cmd_selftest(args):
    """Detector check: a genuinely identical pair must stay silent, a one-field edit must be found."""
    session = Path(args.session).resolve()
    a, afull = read_trace(session / "replay1/trace.csv")
    b_path = session / "replay2/trace.csv"
    b, bfull = read_trace(b_path)
    start = args.skip + 1
    control, control_why = scan(a, afull, b, bfull, start)
    frame = args.skip + args.frame
    lines = b_path.read_text(encoding="utf-8").splitlines()
    row = next(i for i, l in enumerate(lines) if l.startswith(f"{frame},"))
    cols = lines[row].split(",")
    cols[4] = str(int(cols[4]) + 1)                      # the x column, one pixel off
    lines[row] = ",".join(cols)
    out = session / "diff"
    out.mkdir(exist_ok=True)
    inj = out / "injected.csv"
    inj.write_text("\n".join(lines) + "\n", encoding="utf-8")
    bi, bifull = read_trace(inj)
    found, why = scan(a, afull, bi, bifull, start)
    report = {"session": str(session), "framesCompared": len(a), "skippedPowerOn": args.skip,
              "controlPair": {"firstDivergence": control, "fields": control_why},
              "injected": {"frame": frame, "edit": f"x +1 in the second replay at frame {frame}",
                           "firstDivergence": found, "fields": why},
              "detected": control is None and found == frame}
    (out / "selftest.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))
    if not report["detected"]:
        raise SystemExit("the divergence detector failed its own test")


BUFFER_STRIDE = 2048 + 2048 + 256 + 32
BUFFER_SECTIONS = (("nametable", 2048, 4096), ("OAM", 4096, 4352), ("palette", 4352, 4384))


def compare_buffer_bytes(original: bytes, port: bytes, start=1):
    """Compare byte streams, never their additive checksums. RAM outside the mapped fields is excluded."""
    if len(original) % BUFFER_STRIDE or len(port) % BUFFER_STRIDE:
        raise ValueError("Truncated buffer record")
    count = min(len(original), len(port)) // BUFFER_STRIDE
    report = {"framesOriginal": len(original)//BUFFER_STRIDE, "framesPort": len(port)//BUFFER_STRIDE,
              "range": [start, count], "sections": {}}
    for name, lo, hi in BUFFER_SECTIONS:
        ah, bh = hashlib.sha256(), hashlib.sha256()
        matched = 0
        first = None
        for frame in range(start, count + 1):
            base = (frame - 1) * BUFFER_STRIDE
            a, b = original[base+lo:base+hi], port[base+lo:base+hi]
            ah.update(a); bh.update(b)
            if a == b:
                matched += 1
            elif first is None:
                offset = next(i for i, pair in enumerate(zip(a,b)) if pair[0] != pair[1])
                first = {"frame": frame, "offset": offset, "original": a[offset], "port": b[offset]}
        report["sections"][name] = {"matchingFrames": matched, "firstDifference": first,
                                     "originalSha256": ah.hexdigest(), "portSha256": bh.hexdigest()}
    return report


def cmd_buffers(args):
    a, b = Path(args.original).read_bytes(), Path(args.port).read_bytes()
    report = compare_buffer_bytes(a, b, args.start)
    # Detector control: exchanging two unequal bytes preserves the sum but must fail byte equality.
    probe = bytearray(BUFFER_STRIDE); probe[2048:2050] = bytes((1,2))
    swapped = bytearray(probe); swapped[2048:2050] = bytes((2,1))
    control = compare_buffer_bytes(probe, probe)
    injection = compare_buffer_bytes(probe, swapped)
    report["detectorControls"] = {
        "identicalPasses": all(x["firstDifference"] is None for x in control["sections"].values()),
        "sameSumSwapDetected": sum(probe)==sum(swapped) and
            injection["sections"]["nametable"]["firstDifference"] ==
            {"frame":1,"offset":0,"original":1,"port":2}}
    print(json.dumps(report, indent=2))


def compare_route_states(a, b, start, end, include_audio=False):
    """Only explicitly mapped RAM fields; inactive object leftovers are outside this check."""
    if len(a) % BUFFER_STRIDE or len(b) % BUFFER_STRIDE:
        raise ValueError("Truncated buffer record")
    if include_audio and len(a) != len(b):
        raise ValueError("Audio state comparison requires equal complete capture lengths")
    counts = [len(x) // BUFFER_STRIDE for x in (a, b)]
    if not 1 <= start <= end <= min(counts):
        raise ValueError("Requested state window is absent")
    player = [0x50,0x51,0x52,0x53,0x54,0x56,0x5F,0x60,0x61,0x7C,0x98,0x3B,
              0x400,0x410,0x420,0x430,0x460,0x470,0x4D0,0x4F0,0x500,0x510,0x520,
              0x530,0x540,0x550,0x560]
    groups = {
        "player": player,
        "RNG_boss": [0xE4,0xE5,0xE6,0xE7,0xED,0xEE,0xEF],
        "HUD_score_lives": list(range(0x5B0,0x5C2)) + list(range(0x5C4,0x5CE,2)) + [0x5E4,0x5E6,0x6B],
        "progress": [0x31,0x38,0x69],
        "active_objects": None,
    }
    if include_audio:
        groups["audio_persistent"] = [0xC0, *range(0xC7, 0xE4), *range(0x700, 0x780)]
    report = {"framesOriginal":counts[0],"framesPort":counts[1],"range":[start,end],
              "scope":"Mapped fields only; object slots 1..15, all 27 fields $0400..$05A0 when active. No full-RAM or image identity claim.","groups":{}}
    if include_audio:
        report["scope"] += " Audio: $C0/$C7-$E3/$0700-$077F, not scratch $C1-$C6, APU or PCM. Port requires --audio-state capture."
    for name, fields in groups.items():
        ah,bh=hashlib.sha256(),hashlib.sha256(); matched=0; first=None
        for frame in range(start,end+1):
            base=(frame-1)*BUFFER_STRIDE
            if fields is not None:
                av=bytes(a[base+o] for o in fields); bv=bytes(b[base+o] for o in fields)
                offsets=fields
            else:
                aa,bb=bytearray(),bytearray(); offsets=[]
                for slot in range(1,16):
                    live=[bool(x[base+0x4D0+slot]&0x80) for x in (a,b)]
                    # Fixed shape on both sides: union of active slots, with an activity byte.
                    aa.append(int(live[0]));bb.append(int(live[1]));offsets.append(0x4D0+slot)
                    if any(live):
                        for o in range(0x400+slot,0x5B0+slot,16):
                            aa.append(a[base+o]);bb.append(b[base+o]);offsets.append(o)
                av,bv=bytes(aa),bytes(bb)
            ah.update(av);bh.update(bv)
            if av==bv: matched+=1
            elif first is None:
                i=next(i for i,(x,y) in enumerate(zip(av,bv)) if x!=y)
                first={"frame":frame,"address":f"${offsets[i]:04X}","original":av[i],"port":bv[i]}
        report["groups"][name]={"matchingFrames":matched,"firstDifference":first,
            "originalSha256":ah.hexdigest(),"portSha256":bh.hexdigest()}
    report["matched"]=all(v["firstDifference"] is None for v in report["groups"].values())
    return report


def cmd_states(args):
    a,b=Path(args.original).read_bytes(),Path(args.port).read_bytes()
    if args.audio:
        spec = json.loads((Path(args.port).parent / "spec.json").read_text(encoding="utf-8-sig"))
        if spec.get("audioState") is not True:
            raise ValueError("Port capture does not declare --audio-state diagnostic fields")
    if args.end is None and len(a)!=len(b):
        raise ValueError("Different capture lengths; use an explicit diagnostic window")
    report=compare_route_states(a,b,args.start,args.end or len(a)//BUFFER_STRIDE,args.audio)
    print(json.dumps(report,indent=2))
    if not report["matched"]: raise SystemExit(1)


def cmd_scene(args):
    """Check a real scene/Player run against Core at the same pre-input boundary."""
    route=json.loads(Path(args.route).read_text(encoding="utf-8-sig"))
    spec=route["input"];track=track_bytes(Path(args.session));n=len(track)
    if not spec.get("captureAtStart") or spec["frames"]!=n:
        raise ValueError("Requires the complete track and explicit pre-input snapshots")
    fed=bytearray(n)
    for entry in spec["inputs"]:
        if not 1<=entry["first"]<=entry["last"]<=n: raise ValueError("Input range outside track")
        for f in range(entry["first"],entry["last"]+1): fed[f-1]|=entry["buttons"]
    if bytes(fed)!=track: raise ValueError("Scene input differs from the recording")
    core=Path(args.core);raw=(core/"buffers.bin").read_bytes()
    if len(raw)!=n*BUFFER_STRIDE: raise ValueError("Core capture is incomplete")
    import csv
    trace_lines=(core/"trace.csv").read_text(encoding="utf-8-sig").splitlines()
    trace_rows=list(csv.DictReader(line for line in trace_lines if not line.startswith("#")))
    if not trace_rows or any("gameFrame" not in row for row in trace_rows):
        raise ValueError("Missing Core gameFrame export; recapture the trace")
    rows={int(row["frame"]):row for row in trace_rows}
    if len(trace_rows)!=n or set(rows)!=set(range(1,n+1)):
        raise ValueError("Incomplete/duplicate Core trace polls")
    final_clocks=[int(line.split("=",1)[1]) for line in trace_lines if line.startswith("# finalGameFrame=")]
    if len(final_clocks)!=1: raise ValueError("Missing/duplicate Core final gameFrame")
    byframe={int(s["frame"]):s for s in route["states"]}
    if len(byframe)!=len(route["states"]) or not set(byframe).issubset(rows):
        raise ValueError("Duplicate/out-of-range scene snapshots")
    if any(f not in byframe for f in spec["captures"]): raise ValueError("Requested scene snapshot missing")
    sys.path.insert(0,str(ROOT/"Art/Tools/DarkwingResearch"))
    from compare_frames import read_png_rgb, MESEN_2C02
    colors=[v.to_bytes(3,"big") for v in MESEN_2C02]
    fresh_shots=set(json.loads((core/"spec.json").read_text())["captures"])
    errors=[];rgb_checked=0
    for f,s in byframe.items():
        r=rows[f];k=(f-1)*BUFFER_STRIDE;b=raw[k:k+BUFFER_STRIDE]
        expected={key:int(r[key]) for key in ["x","y","state","world","phaseFrames","scrollX","chr0","chr1","ctrl","mask","completed","maskCompleted"]}
        expected.update(gameFrame=int(r["gameFrame"]),phase=r["phase"],scrollY=(b[0xFB]<<8)|b[0xFA],
            scoreUnits=sum((b[0x5C4+i*2]&15)*10**(4-i) for i in range(5)),
            livesLeft=b[0x5E4],livesRight=b[0x5E6],bossDamage=b[0xEE])
        for key,value in expected.items():
            if s[key]!=value: errors.append({"frame":f,"field":key,"core":value,"scene":s[key]})
        for key,lo,hi in [("nametable",2048,4096),("oam",4096,4352),("palette",4352,4384)]:
            got=base64.b64decode(s[key])
            # Ppu exposes a 4 KiB address window; the stand records the 2 KiB
            # physical CIRAM ($2800/$2C00 mirror $2000/$2400 on the NES).
            if key=="nametable":
                if len(got)!=4096: raise ValueError("Unexpected scene nametable window")
                got=got[:2048]
            if got!=b[lo:hi]: errors.append({"frame":f,"field":key})
        if f in fresh_shots:
            w,h,rgb=read_png_rgb(core/f"frame_{f}.png")
            got=b"".join(colors[i&63] for i in base64.b64decode(s["framebuffer"]))
            if (w,h)!=(256,240) or rgb!=got: errors.append({"frame":f,"field":"framebuffer RGB"})
            rgb_checked+=1
    final=route.get("final",{})
    if final.get("frame")!=n: errors.append({"field":"final input frame","expected":n,"got":final.get("frame")})
    if final.get("gameFrame")!=final_clocks[0]: errors.append({"field":"final gameFrame","expected":final_clocks[0],"got":final.get("gameFrame")})
    print(json.dumps({"editor":route["editor"],"framesConsumed":final.get("frame"),"gameFramesAdvanced":final.get("gameFrame"),
        "inputSha256":hashlib.sha256(track).hexdigest(),"snapshotsChecked":len(byframe),"RGBchecked":rgb_checked,
        "boundary":"same pre-input poll number; no input offset", "matchedCore":not errors,"errors":errors[:12],
        "final":{k:final.get(k) for k in ["phase","world","x","y","state","completed","maskCompleted","scoreUnits","livesLeft","livesRight"]}},indent=2))
    if errors: raise SystemExit(1)


