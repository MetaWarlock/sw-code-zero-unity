b=open('D:/Art/SW Code Zero Unity/Research/DarkwingDuck/extracted/raw/prg.bin','rb').read()
base5=5*0x4000
lo=b[base5+0x3429:base5+0x3429+0xC8]   # $B429 (bank5) lo pointers, 199 entries
hi=b[base5+0x34F0:base5+0x34F0+0xC8]   # $B4F0 hi
for a in [0x01,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0B,0x0C,0x0D,0x0E,0x0F,0x11,0x12,0x13,0x14,0x16,0x17,0x18,0x19,0x1A,0x29,0x2D,0x30,0x32,0x33,0x3A,0x3C,0x4D,0x5D]:
    p=hi[a]*256+lo[a]
    off=p-0x8000
    entry=b[base5+off:base5+off+12]
    last=entry[0]&0x7F; dur=entry[1]
    frames=[]
    for i in range(min(last+1,5)):
        fp=entry[2+i*2]|(entry[3+i*2]<<8)
        frames.append(fp)
    print('anim %02X: ptr=$%04X last=%d dur=%d frames=%s' % (a,p,last,dur,[hex(f) for f in frames]))
